const NO_TOOLS_TRAILER =
  '\n\nリマインダー: ツールを一切呼び出さないこと。プレーンテキストのみで回答すること — ' +
  '<analysis> ブロックの後に <summary> ブロック。' +
  'ツール呼び出しは拒否され、タスクに失敗することになる。'

export function getPartialCompactPrompt(
  customInstructions?: string,
  direction: PartialCompactDirection = 'from',
): string {
  const template =
    direction === 'up_to'
      ? PARTIAL_COMPACT_UP_TO_PROMPT
      : PARTIAL_COMPACT_PROMPT
  let prompt = NO_TOOLS_PREAMBLE + template

  if (customInstructions && customInstructions.trim() !== '') {
    prompt += `\n\n追加指示:\n${customInstructions}`
  }

  prompt += NO_TOOLS_TRAILER

  return prompt
}

export function getCompactPrompt(customInstructions?: string): string {
  let prompt = NO_TOOLS_PREAMBLE + BASE_COMPACT_PROMPT

  if (customInstructions && customInstructions.trim() !== '') {
    prompt += `\n\n追加指示:\n${customInstructions}`
  }

  prompt += NO_TOOLS_TRAILER

  return prompt
}

/**
 * <analysis> 下書きスクラッチパッドを取り除き、<summary> XML タグを
 * 読みやすいセクションヘッダーに置き換えてコンパクトサマリをフォーマットする。
 * @param summary <analysis> および <summary> XML タグを含む可能性のある生のサマリ文字列
 * @returns 分析が除去され、サマリタグがヘッダーに置き換えられたフォーマット済みサマリ
 */
export function formatCompactSummary(summary: string): string {
  let formattedSummary = summary

  // analysis セクションを除去 — サマリの品質を向上させる下書きスクラッチパッドだが、
  // サマリが書かれた後は情報的な価値を持たない。
  formattedSummary = formattedSummary.replace(
    /<analysis>[\s\S]*?<\/analysis>/,
    '',
  )

  // summary セクションを抽出してフォーマットする
  const summaryMatch = formattedSummary.match(/<summary>([\s\S]*?)<\/summary>/)
  if (summaryMatch) {
    const content = summaryMatch[1] || ''
    formattedSummary = formattedSummary.replace(
      /<summary>[\s\S]*?<\/summary>/,
      `Summary:\n${content.trim()}`,
    )
  }

  // セクション間の余分な空白を除去する
  formattedSummary = formattedSummary.replace(/\n\n+/g, '\n\n')

  return formattedSummary.trim()
}

export function getCompactUserSummaryMessage(
  summary: string,
  suppressFollowUpQuestions?: boolean,
  transcriptPath?: string,
  recentMessagesPreserved?: boolean,
): string {
  const formattedSummary = formatCompactSummary(summary)

  let baseSummary = `このセッションは、コンテキストが不足した以前の会話から継続しています。以下のサマリは会話の以前の部分をカバーしています。

${formattedSummary}`

  if (transcriptPath) {
    baseSummary += `\n\nコンパクション前の特定の詳細（正確なコードスニペット、エラーメッセージ、生成したコンテンツなど）が必要な場合は、完全なトランスクリプトを読んでください: ${transcriptPath}`
  }

  if (recentMessagesPreserved) {
    baseSummary += `\n\n最近のメッセージはそのまま保持されています。`
  }

  if (suppressFollowUpQuestions) {
    let continuation = `${baseSummary}
ユーザーにそれ以上質問することなく、中断したところから会話を続けること。直接再開すること — サマリを確認したり、何が起きていたかを振り返ったり、「続けます」などと前置きしたりしないこと。中断がなかったかのように最後のタスクを再開すること。`

    if (
      (feature('PROACTIVE') || feature('KAIROS')) &&
      proactiveModule?.isProactiveActive()
    ) {
      continuation += `

あなたは自律的/プロアクティブモードで動作しています。これは最初のウェイクアップではありません — コンパクション前にすでに自律的に作業していました。作業ループを継続すること: 上記のサマリに基づいて中断したところから再開すること。ユーザーに挨拶したり、何に取り組むか尋ねたりしないこと。`
    }

    return continuation
  }

  return baseSummary
}
