// dream.ts から分離して抽出済み。これにより auto-dream が KAIROS フィーチャーフラグに依存せず
// 独立して動作できる（dream.ts は feature() でゲートされた require の背後にある）。

import {
  DIR_EXISTS_GUIDANCE,
  ENTRYPOINT_NAME,
  MAX_ENTRYPOINT_LINES,
} from '../../memdir/memdir.js'

export function buildConsolidationPrompt(
  memoryRoot: string,
  transcriptDir: string,
  extra: string,
): string {
  return `# Dream: メモリ統合

あなたは dream（夢）を実行しています。これはメモリファイルを反省的に見直すパスです。最近学んだことを耐久性のある、整理されたメモリへと統合してください。将来のセッションが素早く状況把握できるようにするためです。

メモリディレクトリ: \`${memoryRoot}\`
${DIR_EXISTS_GUIDANCE}

セッションのトランスクリプト: \`${transcriptDir}\`（大きな JSONL ファイル — 絞り込んで grep すること。ファイル全体を読まないこと）

---

## フェーズ 1 — 現状把握

- メモリディレクトリを \`ls\` して何が存在するか確認する
- \`${ENTRYPOINT_NAME}\` を読んで現在のインデックスを理解する
- 既存のトピックファイルをざっと確認し、重複を作らず改善できるようにする
- \`logs/\` または \`sessions/\` サブディレクトリが存在する場合（assistant モードのレイアウト）、そこの最近のエントリを確認する

## フェーズ 2 — 最近のシグナルを収集する

永続化する価値のある新しい情報を探す。優先度のおおよその順番:

1. **デイリーログ** (\`logs/YYYY/MM/YYYY-MM-DD.md\`) が存在する場合 — これは追記のみのストリーム
2. **ドリフトした既存メモリ** — コードベースの現状と矛盾している事実
3. **トランスクリプト検索** — 特定のコンテキストが必要な場合（例：「昨日のビルド失敗のエラーメッセージは何だったか？」）、JSONL トランスクリプトを絞り込んだ用語で grep する:
   \`grep -rn "<絞り込んだ用語>" ${transcriptDir}/ --include="*.jsonl" | tail -50\`

トランスクリプトを網羅的に読まないこと。すでに重要だと思われるものだけを探せ。

## フェーズ 3 — 統合する

覚えておく価値があるものについて、メモリディレクトリのトップレベルにメモリファイルを書くか更新する。保存する内容、構造化の方法、保存してはいけないものについては、システムプロンプトの auto-memory セクションのメモリファイルフォーマットと型規約を参照すること — そちらが正典だ。

重点を置くこと:
- 重複に近いものを新規作成するのではなく、既存のトピックファイルに新しいシグナルをマージする
- 相対的な日付（「昨日」「先週」）を絶対的な日付に変換して、時間が経っても解釈できるようにする
- 矛盾した事実を削除する — 今日の調査が古いメモリを否定するなら、ソースで修正する

## フェーズ 4 — 剪定とインデックス更新

\`${ENTRYPOINT_NAME}\` を更新して ${MAX_ENTRYPOINT_LINES} 行未満かつ約25KB以下に保つ。これは**インデックス**であってダンプではない — 各エントリは1行で約150文字以内: \`- [タイトル](file.md) — 一行のフック\`。メモリの内容を直接書き込まないこと。

- 古くなった、間違っている、または上書きされたメモリへのポインタを削除する
- 冗長なエントリを縮小する: インデックス行が約200文字を超えている場合、それはトピックファイルに属すべき内容を持っている — 行を短くして詳細を移動する
- 新しく重要になったメモリへのポインタを追加する
- 矛盾を解消する — 2つのファイルが食い違っている場合、間違っている方を修正する

---

統合、更新、または剪定した内容の簡潔なサマリを返すこと。何も変わらなかった場合（メモリがすでに整理されている場合）は、そう述べること。${extra ? `\n\n## 追加コンテキスト\n\n${extra}` : ''}`
}
