/**
 * メモリタイプの分類体系。
 *
 * メモリは、現在のプロジェクト状態から導出できないコンテキストを捉える
 * 4つのタイプに制約されています。コードパターン、アーキテクチャ、gitの履歴、
 * ファイル構造は導出可能（grep/git/CLAUDE.md経由）であり、メモリとして
 * 保存すべきではありません。
 *
 * 以下の2つのTYPES_SECTION_*エクスポートは、共有仕様から生成するのではなく
 * 意図的に複製されています——フラットに保つことで、ヘルパーの条件付きレンダリングを
 * 考慮することなく、モードごとの編集が容易になります。
 */

export const MEMORY_TYPES = [
  'user',
  'feedback',
  'project',
  'reference',
] as const

export type MemoryType = (typeof MEMORY_TYPES)[number]

/**
 * 生のフロントマター値をMemoryTypeにパースする。
 * 無効または欠落した値はundefinedを返します——`type:`フィールドのない
 * レガシーファイルは引き続き動作し、未知のタイプのファイルはグレースフルに劣化します。
 */
export function parseMemoryType(raw: unknown): MemoryType | undefined {
  if (typeof raw !== 'string') return undefined
  return MEMORY_TYPES.find(t => t === raw)
}

