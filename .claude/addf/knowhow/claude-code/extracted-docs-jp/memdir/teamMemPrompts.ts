import {
  buildSearchingPastContextSection,
  DIRS_EXIST_GUIDANCE,
  ENTRYPOINT_NAME,
  MAX_ENTRYPOINT_LINES,
} from './memdir.js'
import {
  MEMORY_DRIFT_CAVEAT,
  MEMORY_FRONTMATTER_EXAMPLE,
  TRUSTING_RECALL_SECTION,
  TYPES_SECTION_COMBINED,
  WHAT_NOT_TO_SAVE_SECTION,
} from './memoryTypes.js'
import { getAutoMemPath } from './paths.js'
import { getTeamMemPath } from './teamMemPaths.js'

/**
 * 自動メモリとチームメモリの両方が有効な場合の結合プロンプトを構築する。
 * per-type <scope>ガイダンスをXMLスタイルの<type>ブロックに埋め込んだ
 * クローズドな4タイプ分類（user / feedback / project / reference）。
 */
export function buildCombinedMemoryPrompt(
  extraGuidelines?: string[],
  skipIndex = false,
): string {
  const autoDir = getAutoMemPath()
  const teamDir = getTeamMemPath()

  const howToSave = skipIndex
    ? [
        '## メモリの保存方法',
        '',
        'タイプのスコープガイダンス（プライベートまたはチーム）に従い、選択したディレクトリに各メモリを個別のファイルとして、以下のフロントマター形式で書き込んでください:',
        '',
        ...MEMORY_FRONTMATTER_EXAMPLE,
        '',
        '- メモリファイルの name、description、type フィールドを内容と一致した状態に保つこと',
        '- メモリはトピックごとに意味的に整理し、時系列では整理しないこと',
        '- 誤りや古くなったメモリは更新または削除すること',
        '- メモリを重複して書かないこと。新しいメモリを書く前に、更新できる既存のメモリがないか先に確認すること。',
      ]
    : [
        '## メモリの保存方法',
        '',
        'メモリの保存は2ステップのプロセスです:',
        '',
        '**ステップ1** — タイプのスコープガイダンス（プライベートまたはチーム）に従い、選択したディレクトリに以下のフロントマター形式でメモリを個別のファイルとして書き込んでください:',
        '',
        ...MEMORY_FRONTMATTER_EXAMPLE,
        '',
        `**ステップ2** — 同じディレクトリの \`${ENTRYPOINT_NAME}\` にそのファイルへのポインタを追加してください。各ディレクトリ（プライベートとチーム）にはそれぞれ独自の \`${ENTRYPOINT_NAME}\` インデックスがあります — 各エントリは1行で、150文字以内にしてください: \`- [タイトル](file.md) — 一行の説明\`。フロントマターは不要です。メモリの内容を直接 \`${ENTRYPOINT_NAME}\` に書き込まないこと。`,
        '',
        `- 両方の \`${ENTRYPOINT_NAME}\` インデックスは会話コンテキストに読み込まれます — ${MAX_ENTRYPOINT_LINES} 行以降は切り捨てられるため、簡潔に保つこと`,
        '- メモリファイルの name、description、type フィールドを内容と一致した状態に保つこと',
        '- メモリはトピックごとに意味的に整理し、時系列では整理しないこと',
        '- 誤りや古くなったメモリは更新または削除すること',
        '- メモリを重複して書かないこと。新しいメモリを書く前に、更新できる既存のメモリがないか先に確認すること。',
      ]

  const lines = [
    '# メモリ',
    '',
    `あなたはファイルベースの永続的なメモリシステムを持ち、2つのディレクトリが利用できます: \`${autoDir}\` のプライベートディレクトリと \`${teamDir}\` の共有チームディレクトリです。${DIRS_EXIST_GUIDANCE}`,
    '',
    'このメモリシステムを時間をかけて構築し、将来の会話でユーザーが何者であるか、どのようにコラボレーションしたいか、避けるべきまたは繰り返すべき行動、ユーザーから与えられる作業の背景について完全な情報を得られるようにしてください。',
    '',
    'ユーザーが何かを覚えてほしいと明示的に求めた場合は、最も適切なタイプとして即座に保存してください。忘れてほしいと求めた場合は、該当するエントリを見つけて削除してください。',
    '',
    '## メモリのスコープ',
    '',
    'スコープには2つのレベルがあります:',
    '',
    `- プライベート: あなたと現在のユーザーの間だけのプライベートなメモリ。特定のユーザーとの会話をまたいで保持され、ルートの \`${autoDir}\` に保存されます。`,
    `- チーム: このプロジェクトディレクトリ内で作業するすべてのユーザーが共有・追加できるメモリ。チームメモリは各セッション開始時に同期され、\`${teamDir}\` に保存されます。`,
    '',
    ...TYPES_SECTION_COMBINED,
    ...WHAT_NOT_TO_SAVE_SECTION,
    '- 共有チームメモリに機密データを保存することは避けること。例えば、APIキーやユーザー認証情報は絶対に保存しないこと。',
    '',
    ...howToSave,
    '',
    '## メモリにアクセスするタイミング',
    '- 個人またはチームのメモリが関連しそうな場合、またはユーザーが自分または組織内の他の人との過去の作業に言及した場合。',
    '- ユーザーがメモリを確認、想起、または記憶するよう明示的に求めた場合は、必ずメモリにアクセスすること。',
    '- ユーザーがメモリを*無視する*または*使用しない*と言った場合: MEMORY.md が空であるかのように進めること。記憶した事実を適用したり、引用したり、比較したり、メモリの内容に言及しないこと。',
    MEMORY_DRIFT_CAVEAT,
    '',
    ...TRUSTING_RECALL_SECTION,
    '',
    '## メモリとその他の永続化手段',
    'メモリは、特定の会話でユーザーをサポートする際に利用できる複数の永続化メカニズムの1つです。メモリは将来の会話で想起できるという点で区別されており、現在の会話のスコープ内でのみ有用な情報の永続化には使用しないことが重要です。',
    '- メモリの代わりにプランを使用または更新するタイミング: 非自明な実装タスクを開始しようとしており、アプローチについてユーザーと合意を得たい場合は、この情報をメモリに保存するのではなくプランを使用してください。同様に、会話内にすでにプランがあり、アプローチを変更した場合は、メモリを保存するのではなくプランを更新してその変更を永続化してください。',
    '- メモリの代わりにタスクを使用または更新するタイミング: 現在の会話での作業を個別のステップに分割したり、進捗を追跡する必要がある場合は、メモリに保存する代わりにタスクを使用してください。タスクは現在の会話で行う必要がある作業の情報を永続化するのに適していますが、メモリは将来の会話で有用となる情報のために取っておくべきです。',
    ...(extraGuidelines ?? []),
    '',
    ...buildSearchingPastContextSection(autoDir),
  ]

  return lines.join('\n')
}
